N_TOTAL = sum(sum(v) for v in POP.values())  # 36,864,414 이어야 함


def pop_count(province_code, sex_code, age_group):
    return POP[(province_code, sex_code)][age_group]


def compute_weights(records):
    """records: [{stratum:{province_code,sex_code,age_group}}, ...].
    각 응답자의 사후층화 가중치(평균 1, 합=n) 리스트 반환."""
    n = len(records)
    # 표본 셀 빈도
    sample_cnt = {}
    for r in records:
        s = r["stratum"]
        key = (s["province_code"], s["sex_code"], s["age_group"])
        sample_cnt[key] = sample_cnt.get(key, 0) + 1
    raw = []
    for r in records:
        s = r["stratum"]
        key = (s["province_code"], s["sex_code"], s["age_group"])
        pop_share = pop_count(*key) / N_TOTAL
        smp_share = sample_cnt[key] / n
        raw.append(pop_share / smp_share)
    # 평균 1로 정규화
    mean = sum(raw) / n
    return [w / mean for w in raw]


def compute_engagement_weights(records):
    """Existing post-stratification weights plus optional engagement adjustment."""
    from engagement import engagement_factors
    base = compute_weights(records)
    factors = engagement_factors(records)
    combined = [w * f for w, f in zip(base, factors)]
    mean = sum(combined) / len(combined) if combined else 1.0
    return [w / mean for w in combined]


